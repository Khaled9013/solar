class ModelHandler(BaseHTTPRequestHandler):
    def log_message(self, *args):
        pass

    def do_GET(self):
        body = json.dumps({"data":[{"id":"solar-test"}]}).encode()
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_POST(self):
        data = json.loads(self.rfile.read(int(self.headers.get("Content-Length", 0))))
        messages = data.get("messages", [])
        if data.get("tools") and messages[-1].get("role") != "tool":
            delta = {"tool_calls":[{"index":0,"id":"test-file-call","function":{"name":"write_file","arguments":json.dumps({"path":"codex/files/result.txt","content":"A test deliverable generated by the local mock model.\n"})}}]}
            deltas = [delta]
        else:
            deltas = [{"content":"Your task is complete. "},{"content":"I created result.txt in the session's codex/files folder.\n\n"},{"content":"```python\nprint('Ready to build')\n```\n\nEverything stays together in this workspace."}]
        body = ("".join("data: "+json.dumps({"choices":[{"delta":d}]})+"\n\n" for d in deltas)+"data: [DONE]\n\n").encode()
        self.send_response(200)
        self.send_header("Content-Type", "text/event-stream")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)


model = ThreadingHTTPServer(("127.0.0.1",5569), ModelHandler)
